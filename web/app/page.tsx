  const finishRecording = useCallback(async (cancelled = false, meta?: { reason?: string }) => {
    setViewMode("voice");
    const recorder = recorderRef.current;
    if (!recorder) return;
    recorderRef.current = null;
    const stopResult = stopRecorderTurn(recorder, {
      reason: meta?.reason || (cancelled ? "cancelled" : "utterance"),
      releaseStream: false,
    });
    isRecordingFlagRef.current = false;
    setIsRecording(false); setAmplitude(0.2); setBands({ bass: 0, treble: 0 }); setAutoStopProgress(0); setMicLevel(0);

    // Early teardown without speech → one guarded reopen (not user stop / real utterance).
    const reopenBlocked = new Set(["user_stop", "utterance", "prepare_tts", "new_chat", "page_unload"]);
    if (
      stopResult.early &&
      !recorder.heardSpeech &&
      !earlyReopenUsedRef.current &&
      !reopenBlocked.has(stopResult.reason) &&
      (voiceLoopRef.current.state === "listening" || voiceLoopRef.current.state === "idle")
    ) {
      earlyReopenUsedRef.current = true;
      voiceClientLog("teardown_early_reopen", {
        turn_id: stopResult.turnId,
        reason: stopResult.reason,
        age_ms: stopResult.ageMs,
      });
      const turn = voiceLoopRef.current.beginTurn();
      speakTurnIdRef.current = turn;
      voiceLoopRef.current.transition("idle", "teardown_early_reopen");
      resumeListening(turn);
      return;
    }

    const sttSession = browserSttRef.current;
    browserSttRef.current = null;
    const spokenMs = speechMs(recorder);
    const tooLittleSpeech = !cancelled && recorder.heardSpeech && spokenMs < MIN_SPEECH_MS;
    if (cancelled || !recorder.heardSpeech || tooLittleSpeech) {
      sttSession?.abort();
      orbStateRef.current = "idle";
      setOrbState("idle");
      if (tooLittleSpeech && noiseDiscardsRef.current < 3) {
        noiseDiscardsRef.current += 1;
        debugLog("[Setu mic] ignored noise", { speechMs: Math.round(spokenMs) });
        const turn = voiceLoopRef.current.beginTurn();
        speakTurnIdRef.current = turn;
        voiceLoopRef.current.transition("idle", "noise_discard");
        resumeListening(turn);
        return;
      }
      noiseDiscardsRef.current = 0;
      if (meta?.reason === "no_speech") {
        noSpeechTimeoutsRef.current += 1;
        if (noSpeechTimeoutsRef.current >= 2 && !vadHintShownRef.current) {
          vadHintShownRef.current = true;
          voiceClientLog("vad_hint_shown", { count: noSpeechTimeoutsRef.current });
          setStatusText("Speak closer to the phone");
          return;
        }
      }
      setStatusText("Tap to continue");
      return;
    }
    // Endpoint fired → leave "Listening…" immediately, before any STT round-trip.
    voiceLoopRef.current.transition("thinking", "utterance_submitted");
    orbStateRef.current = "processing";
    setOrbState("processing"); setStatusText("Hearing you"); setService("SAARAS");
    // Browser STT is optional early feedback; failures must not block server Saaras.
    let browserTranscript = "";
    if (sttSession) {
      try {
        if (sttSession.unavailable()) {
          voiceLoopRef.current.noteBrowserSttUnavailable();
          browserTranscript = "";
        } else {
          browserTranscript = await sttSession.stop();
          if (sttSession.unavailable()) voiceLoopRef.current.noteBrowserSttUnavailable();
        }
      } catch {
        browserTranscript = "";
        sttSession.abort();
      }
    }
    if (browserTranscript) {
      debugLog("[browser-stt]", { chars: browserTranscript.length, text: browserTranscript.slice(0, 80) });
      // Display-only; the turn uses server STT transcript from the response.
      setTranscript(browserTranscript);
    }
    turnTimingRef.current = emptyTurnTiming();
    try {
      const wav = recorderToWav(recorder);
      const activeSession = sessionsRef.current.find((item) => item.id === activeSessionIdRef.current);
      const loadedDocId = docIdRef.current;
      const history = getHistoryPayload();
      const memory = getMemoryPayload();
      const voiceStarted = performance.now();
      const sessionCfg = {
        language: languageRef.current,
        hasDocument: Boolean(loadedDocId),
        docId: loadedDocId,
        sessionId: activeSessionIdRef.current,
        history,
        memory,
        onboarded: Boolean(activeSession?.onboarded),
        pace,
      };

      let result: VoiceTurnResponse;
      const session = voiceSessionRef.current;
      try {
        await session.updateSession(sessionCfg);
        result = await session.runUtterance(
          wav,
          {
            onStatus: (stage, text) => {
              if (stage === "stt") setService("SAARAS");
              else if (stage === "think") setService("105B");
              else if (stage === "tts") setService("BULBUL");
              if (text) setStatusText(text);
            },
            onTranscript: (text) => {
              if (text) setTranscript(text);
            },
          },
          undefined,
          browserTranscript || null,
        );
        debugLog("[voice] websocket turn", { route: result.route, tools: result.tools_used });
      } catch (wsError) {
        debugLog("[voice] websocket fallback to POST /voice", wsError);
        result = await postVoiceTurn({
          audio: wav,
          language: languageRef.current,
          hasDocument: Boolean(loadedDocId),
          docId: loadedDocId,
          sessionId: activeSessionIdRef.current,
          history,
          memory,
          onboarded: Boolean(activeSession?.onboarded),
          speaker: "shubh",
          pace,
          transcript: browserTranscript || null,
        });
      }
      await processVoiceTurnResult(result, { spokenMs, voiceStarted });
    } catch (error) {
      if (error instanceof Error && error.message === "cancelled") {
        setService(null);
        return;
      }
      setService(null);
      setOrbState("idle");
      const message = error instanceof Error ? error.message : "Something went wrong";
      setStatusText(`${message} — tap to continue`);
      logTurnTiming(turnTimingRef.current);
    }
  }, [addTurn, cameraText, getHistoryPayload, getMemoryPayload, mergeSessionCorrections, openCamera, patchActiveSession, playSpeech, processVoiceTurnResult, resumeListening, speaker, pace]);

