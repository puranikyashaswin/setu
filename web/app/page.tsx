function makeSession(language: Language): Session {
  const now = Date.now();
  return {
    id: crypto.randomUUID(),
    title: "New chat",
    createdAt: now,
    updatedAt: now,
    language,
    docId: null,
    corrections: [],
    turns: [],
    onboarded: false,
    summary: null,
  };
}

function titleFromTurns(turns: Turn[]) {
  const firstUser = turns.find((turn) => (
    turn.role === "user"
    && turn.text !== "Start conversation"
    && turn.text !== "Scanned document"
  ));
  if (firstUser) {
    const words = firstUser.text.trim().split(/\s+/).filter(Boolean).slice(0, 6);
    if (words.length) return words.join(" ");
  }
  // A scan-only chat still deserves a real name, in the list and in cross-chat memory.
  const summary = turns.find((turn) => turn.role === "setu" && turn.kind === "summary");
  if (summary) {
    const words = summary.text.trim().split(/\s+/).filter(Boolean).slice(0, 6);
    if (words.length) return words.join(" ");
  }
  return "New chat";
}

function relativeTime(timestamp: number) {
  const seconds = Math.max(0, Math.floor((Date.now() - timestamp) / 1000));
  if (seconds < 60) return "just now";
  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) return `${minutes}m ago`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.floor(hours / 24);
  if (days < 7) return `${days}d ago`;
  return new Date(timestamp).toLocaleDateString(undefined, { month: "short", day: "numeric" });
}

function dayLabel(timestamp: number) {
  return new Date(timestamp).toLocaleDateString(undefined, { weekday: "long", month: "short", day: "numeric" });
}

function groupSessionsByDay(sessions: Session[]): [string, Session[]][] {
  const sorted = [...sessions].sort((a, b) => b.updatedAt - a.updatedAt);
  const groups = new Map<string, Session[]>();
  for (const session of sorted) {
    const day = dayLabel(session.updatedAt);
    const list = groups.get(day) ?? [];
    list.push(session);
    groups.set(day, list);
  }
  return [...groups.entries()];
}

