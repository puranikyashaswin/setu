function normalizeActionItem(text: string) {
  return text.trim().replace(/\s+/g, " ").toLowerCase();
}

function collectAskExchanges(session: Session): AskExchange[] {
  const exchanges: AskExchange[] = [];
  for (let index = 0; index < session.turns.length - 1; index += 1) {
    const user = session.turns[index];
    const setu = session.turns[index + 1];
    if (user.role !== "user" || setu.role !== "setu") continue;
    if (setu.askMeta?.fromAsk && setu.kind !== "summary") {
      exchanges.push({
        question: user.text,
        answer: setu.text,
        status: setu.askMeta.status,
        abstain: setu.askMeta.abstain,
        actionItems: setu.askMeta.actionItems,
        corrections: setu.askMeta.corrections,
        evidence: setu.evidence ?? [],
      });
      index += 1;
      continue;
    }
    if (
      session.docId
      && setu.kind !== "summary"
      && user.text !== "Start conversation"
      && (setu.evidence?.length ?? 0) > 0
    ) {
      exchanges.push({
        question: user.text,
        answer: setu.text,
        status: "verified_document",
        abstain: false,
        actionItems: [],
        corrections: [],
        evidence: setu.evidence ?? [],
      });
      index += 1;
    }
  }
  return exchanges;
}

function extractDeadline(sources: string[]): string | null {
  const hits: { text: string; score: number }[] = [];
  for (const source of sources) {
    const trimmed = source.trim();
    if (!trimmed) continue;
    if (DEADLINE_HINT.test(trimmed)) {
      const match = trimmed.match(DATE_TOKEN);
      hits.push({ text: match?.[1] ?? trimmed, score: 3 });
      continue;
    }
    const match = trimmed.match(DATE_TOKEN);
    if (match) hits.push({ text: match[1], score: 1 });
  }
  if (!hits.length) return null;
  hits.sort((a, b) => b.score - a.score || b.text.length - a.text.length);
  return hits[0].text;
}

function buildActionSheetExportModel(
  session: Session,
  documentName: string,
  language: Language,
): ActionSheetExportModel {
  const labels = ACTION_SHEET_LABELS[language];
  const exchanges = collectAskExchanges(session);
  const itemMap = new Map<string, ActionSheetExportItem>();
  const officeQuestions: string[] = [];
  const seenQuestions = new Set<string>();
  const deadlineSources: string[] = [];

  for (const exchange of exchanges) {
    deadlineSources.push(exchange.answer, ...exchange.actionItems);
    if (exchange.abstain || exchange.status === "not_found") {
      const key = exchange.question.trim().toLowerCase();
      if (!seenQuestions.has(key) && exchange.question.trim() && exchange.question !== "Scanned document") {
        seenQuestions.add(key);
        officeQuestions.push(exchange.question.trim());
      }
    }
    const verifiedEvidence = exchange.evidence.filter((item) => item.verified);
    for (const actionItem of exchange.actionItems) {
      const trimmed = actionItem.trim();
      if (!trimmed) continue;
      const key = normalizeActionItem(trimmed);
      const existing = itemMap.get(key);
      if (existing) {
        for (const evidence of verifiedEvidence) {
          const duplicate = existing.evidence.some(
            (item) => item.page === evidence.page && item.quote === evidence.quote,
          );
          if (!duplicate) existing.evidence.push({ page: evidence.page, quote: evidence.quote });
        }
      } else {
        itemMap.set(key, {
          text: trimmed,
          evidence: verifiedEvidence.map((item) => ({ page: item.page, quote: item.quote })),
        });
      }
    }
  }

  return {
    labels,
    documentName,
    deadline: extractDeadline(deadlineSources),
    items: [...itemMap.values()],
    officeQuestions,
    corrections: sessionCorrections(session),
    date: new Date().toLocaleDateString(language === "en" ? "en-IN" : `${language}-IN`, {
      year: "numeric",
      month: "long",
      day: "numeric",
    }),
    language,
  };
}

