function turnToAnswerSheet(turn: Turn): AnswerSheet | null {
  if (turn.role !== "setu" || turn.kind === "summary" || !turn.askMeta) return null;
  return {
    answer: turn.text,
    status: turn.askMeta.status,
    abstain: turn.askMeta.abstain,
    all_verified: turn.askMeta.allVerified ?? (
      Boolean(turn.evidence?.length)
      && (turn.evidence ?? []).every((item) => item.verified)
      && turn.askMeta.status === "verified_document"
    ),
    evidence: turn.evidence ?? [],
    corrections: turn.askMeta.corrections,
    action_items: turn.askMeta.actionItems,
  };
}

