const DEADLINE_HINT = /\b(deadline|due date|last date|final date|submit by|before|by when|గడువు|చివరి\s*తేదీ|अंतिम\s*तिथि|கடைசி\s*தேதி)\b/i;
const DATE_TOKEN = /\b(\d{1,2}[\/\-\.]\d{1,2}[\/\-\.]\d{2,4}|\d{1,2}\s+(?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:tember)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?)\s+\d{4}|\d{4}[\/\-\.]\d{1,2}[\/\-\.]\d{1,2})\b/i;

function mergeCorrections(existing: Correction[], incoming: Correction[]): Correction[] {
  const byField = new Map<string, Correction>();
  for (const item of existing) byField.set(item.field, item);
  for (const item of incoming) byField.set(item.field, item);
  return [...byField.values()].sort((a, b) => a.timestamp - b.timestamp);
}

function correctionsFromTurns(turns: Turn[]): Correction[] {
  const byField = new Map<string, Correction>();
  for (const turn of turns) {
    for (const item of turn.askMeta?.corrections ?? []) {
      byField.set(item.field, item);
    }
  }
  return [...byField.values()].sort((a, b) => a.timestamp - b.timestamp);
}

function sessionCorrections(session: Session): Correction[] {
  if (session.corrections?.length) {
    return [...session.corrections].sort((a, b) => a.timestamp - b.timestamp);
  }
  return correctionsFromTurns(session.turns);
}

function hydrateSessionCorrections(session: Session): Session {
  const merged = mergeCorrections(session.corrections ?? [], correctionsFromTurns(session.turns));
  return merged.length ? { ...session, corrections: merged } : session;
}

