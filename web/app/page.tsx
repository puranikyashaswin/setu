function answerSheetHeader(sheet: AnswerSheet): { label: string; tone: "verified" | "abstain" | "caution" | "partial" } {
  if (sheet.status === "not_found" || sheet.abstain) {
    return { label: "This document does not answer that.", tone: "abstain" };
  }
  if (sheet.status === "unclear_scan") {
    return { label: "Parts of this scan could not be read.", tone: "caution" };
  }
  if (sheet.all_verified && sheet.status === "verified_document") {
    return { label: "Verified from document", tone: "verified" };
  }
  return { label: "Partially verified", tone: "partial" };
}

